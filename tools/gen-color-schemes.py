#!/usr/bin/env python3
"""Generate the Singlr KDE colour schemes from the shell's own tokens (Theme.qml/Theme.js),
so applications and the shell share one palette. Output: session/color-schemes/*.colors."""
import colorsys, math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Provisional default accent (Linear indigo) until the creator approves the palette (P-006).
ACCENT = '#5e6ad2'


def hex_rgb(h):
    h = h.lstrip('#'); return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def linear(v): return v / 12.92 if v <= .04045 else ((v + .055) / 1.055) ** 2.4
def gamma(v): return 12.92 * v if v <= .0031308 else 1.055 * v ** (1 / 2.4) - .055


def lch(c):
    r, g, b = map(linear, c)
    f = lambda v: v ** (1 / 3) if v > .008856 else 7.787 * v + 16 / 116
    x = f((.4124564 * r + .3575761 * g + .1804375 * b) / .95047)
    y = f(.2126729 * r + .7151522 * g + .072175 * b)
    z = f((.0193339 * r + .119192 * g + .9503041 * b) / 1.08883)
    L, a, bb = 116 * y - 16, 500 * (x - y), 200 * (y - z)
    return L, math.hypot(a, bb), math.atan2(bb, a)


def color(l, c, h):
    fy = (max(0, min(100, l)) + 16) / 116
    fx, fz = fy + c * math.cos(h) / 500, fy - c * math.sin(h) / 200
    f = lambda v: v ** 3 if v ** 3 > .008856 else (v - 16 / 116) / 7.787
    x, y, z = .95047 * f(fx), f(fy), 1.08883 * f(fz)
    cl = lambda v: max(0, min(1, gamma(v)))
    return (cl(3.2404542 * x - 1.5371385 * y - .4985314 * z), cl(-.969266 * x + 1.8760108 * y + .041556 * z),
            cl(.0556434 * x - .2040259 * y + 1.0572252 * z))


def level(base, offset):
    b = lch(base); return color(b[0] + offset, min(.7, b[1]), b[2])


def ink(base, target):
    b = lch(base); return color(target, min(.8, b[1]), b[2])


def kde(c): return ','.join(str(round(v * 255)) for v in c)


def scheme(dark):
    base = hex_rgb('#08090a' if dark else '#f8f8f8')
    d = (lambda dk, lt: dk if dark else lt)
    window, view, raised = level(base, d(2.1, -1.5)), level(base, d(4.3, 2.5)), level(base, d(6.8, -3.8))
    alt = level(base, d(5.5, 1.0))
    text = hex_rgb('#f7f8f8') if dark else ink(base, 17)
    muted = ink(base, d(72, 39))
    accent = hex_rgb(ACCENT)
    a = lch(accent)
    link = color(d(70, 45), min(60, a[1]), a[2])
    fg = {'ForegroundNormal': text, 'ForegroundInactive': muted, 'ForegroundActive': link, 'ForegroundLink': link,
          'ForegroundVisited': color(d(66, 40), 45, a[2] + .6),
          'ForegroundNegative': hex_rgb(d('#ef9a9a', '#b42d2d')), 'ForegroundNeutral': hex_rgb(d('#f2c94c', '#9a6b00')),
          'ForegroundPositive': hex_rgb(d('#4cb782', '#1f7a4c')), 'DecorationFocus': accent, 'DecorationHover': accent}
    sets = {'Window': (window, alt), 'View': (view, alt), 'Button': (raised, alt), 'Header': (window, view),
            'Header][Inactive': (view, window), 'Tooltip': (raised, view), 'Complementary': (base, window)}
    out = [f'# Generated by tools/gen-color-schemes.py from shell/qml/Singlr/Ui/Theme.qml tokens. Do not edit.',
           '', '[ColorEffects:Disabled]', 'Color=56,56,56', 'ColorAmount=0', 'ColorEffect=0', 'ContrastAmount=0.65',
           'ContrastEffect=1', 'IntensityAmount=0.1', 'IntensityEffect=2', '',
           '[ColorEffects:Inactive]', 'ChangeSelectionColor=true', 'Color=112,111,110', 'ColorAmount=0.025',
           'ColorEffect=2', 'ContrastAmount=0.1', 'ContrastEffect=2', 'Enable=false', 'IntensityAmount=0',
           'IntensityEffect=0', '']
    for name, (bg, bga) in sets.items():
        out += [f'[Colors:{name}]', f'BackgroundAlternate={kde(bga)}', f'BackgroundNormal={kde(bg)}']
        out += [f'{k}={kde(v)}' for k, v in sorted(fg.items())] + ['']
    sel_fg = (1, 1, 1)
    out += ['[Colors:Selection]', f'BackgroundAlternate={kde(level(accent, -8))}', f'BackgroundNormal={kde(accent)}']
    out += [f'{k}={kde(sel_fg if k in ("ForegroundNormal", "ForegroundActive") else v)}' for k, v in sorted(fg.items())] + ['']
    name = 'SinglrDark' if dark else 'SinglrLight'
    out += ['[General]', f'ColorScheme={name}', f'Name=Singlr {"Dark" if dark else "Light"}',
            f'Name[es]=Singlr {"oscuro" if dark else "claro"}', 'shadeSortColumn=true', '',
            '[KDE]', 'contrast=4', '', '[WM]', f'activeBackground={kde(window)}', f'activeBlend={kde(text)}',
            f'activeForeground={kde(text)}', f'inactiveBackground={kde(base)}', f'inactiveBlend={kde(muted)}',
            f'inactiveForeground={kde(muted)}', '']
    return name, '\n'.join(out)


for dark in (True, False):
    name, text = scheme(dark)
    (ROOT / 'session/color-schemes' / f'{name}.colors').write_text(text)
    print(name)
